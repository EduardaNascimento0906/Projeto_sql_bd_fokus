
CREATE TABLE IF NOT EXISTS Colaboradores (
	ID VARCHAR (255),
	Nome	VARCHAR(255),
	DataNascimento	DATE,
	CPF	VARCHAR(14),
	Endereco	VARCHAR(255),
	Telefone	VARCHAR(100),
	Email	VARCHAR(255),
	PRIMARY KEY(ID)
);
CREATE TABLE IF NOT EXISTS Dependentes (
	ID VARCHAR (255),
	ID_Colaborador VARCHAR (255),
	Nome	VARCHAR(255),
	Parentesco	VARCHAR(50),
	DataNascimento	DATE,
	CPF	VARCHAR(14),
	Genero	VARCHAR(15),
	PRIMARY KEY(ID),
	FOREIGN KEY(ID_Colaborador) REFERENCES Colaboradores(ID)
);
CREATE TABLE IF NOT EXISTS HistoricoEmprego (
	ID VARCHAR (255),
	ID_Colaborador VARCHAR (255),
	Cargo	VARCHAR(255),
	DataContratacao	DATE,
	DataTermino	DATE,
	Salario	DECIMAL(10, 2),
	Supervisor	VARCHAR(255),
	PRIMARY KEY(ID),
	FOREIGN KEY(ID_Colaborador) REFERENCES Colaboradores(ID)
);
CREATE TABLE IF NOT EXISTS Licencas (
	ID VARCHAR (255),
	ID_Colaborador	VARCHAR (255),
	TipoLicenca	VARCHAR(255),
	DataInicio	DATE,
	DataFim	DATE,
	PRIMARY KEY(ID),
	FOREIGN KEY(ID_Colaborador) REFERENCES Colaboradores(ID)
);
CREATE TABLE IF NOT EXISTS Treinamento (
	ID VARCHAR (255),
	ID_Colaborador	VARCHAR (255),
	Curso	VARCHAR(255),
	DataConclusao	DATE,
	Instituicao	VARCHAR(255),
	PRIMARY KEY(ID),
	FOREIGN KEY(ID_Colaborador) REFERENCES Colaboradores(ID)
);
CREATE TABLE IF NOT EXISTS faturamento (
	id VARCHAR (255),
	mes	VARCHAR(20),
	faturamento_bruto	DECIMAL(10, 2),
	despesas	DECIMAL(10, 2),
	lucro_liquido	DECIMAL(10, 2),
	numero_clientes	INT,
	numero_novos_clientes	INT,
	PRIMARY KEY(id)
);
